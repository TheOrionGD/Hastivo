export const LANGUAGE_STORAGE_KEY = "hastivo-preferred-language";

export function getStoredLanguage() {
  if (typeof window === "undefined") return "en";
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY) || "en";
  } catch {
    return "en";
  }
}

export function setStoredLanguage(code) {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, code);
    window.dispatchEvent(new CustomEvent("hastivo-language-changed", { detail: code }));
  } catch {}
}

export function getLanguageMetadata(code) {
  return SUPPORTED_LANGUAGES.find((l) => l.code === code) || SUPPORTED_LANGUAGES[0];
}

